/** 收音式缩约：나 + 는 → 난、나 + 를 → 날（只认短词：난、넌、전、이건、그걸……） */
export const CODA_PARTICLES: { t: string; label: string }[] = [
  { t: 'ㄴ', label: '은/는' },
  { t: 'ㄹ', label: '을/를' }
]

export function condOk(cond: ParticleCond, prev: string): boolean {
  const s = decompose(prev.slice(-1))
  // 前面不是韩文（SNS를、TV는、學校에）：读音不知道，两种写法都认
  if (!s) return true
  switch (cond) {
    case 'C':
      return !!s.t
    case 'V':
      return !s.t
    case 'VL':
      return !s.t || s.t === 'ㄹ'
    case 'NL':
      return !!s.t && s.t !== 'ㄹ'
    case 'any':
      return true
  }
}

