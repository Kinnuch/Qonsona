/**
 * 韩语的助词（조사）：体词后面一个个黏上去（학교 + 에서 + 는 → 학교에서는）。
 * 好些助词按前一个音节有没有收音分两种写法（이/가、은/는、을/를、와/과、(으)로……），还原时也按这个核对：
 * 「학교이」不会被当成「학교 + 이」。
 */
import { decompose } from './hangul'

/** 前一个音节的条件：C 有收音、V 没有收音、VL 没有收音或收音是 ㄹ（(으)로 的「로」）、NL 有收音但不是 ㄹ */
export type ParticleCond = 'C' | 'V' | 'VL' | 'NL' | 'any'

export interface Particle {
  /** 写法（音节）；收音式的缩约（난 = 나 + 는）另见 CODA_PARTICLES */
  s: string
  /** 词典式写法，也是标签：이/가、은/는…… */
  label: string
  cond: ParticleCond
  /** 0 最常见；同样对得上的几种分析，常见的排前面 */
  rank: number
  /** 只能出现在最后（은/는、도、요……后面不再接别的助词） */
  final?: boolean
}

const P = (
  s: string,
  label: string,
  cond: ParticleCond,
  rank: number,
  final = false
): Particle => ({
  s,
  label,
  cond,
  rank,
  final
})

