const KANA = /^[ぁ-ゖァ-ヺー]+$/

/** 词表文字 → [写法, 读音]；写法是假名的可以不写读音 */
function parseWords(text) {
  return text
    .trim()
    .split(/\s+/)
    .map((token) => {
      const [written, reading = KANA.test(written) ? written : ''] = token.split('/')
      return [written, reading]
    })
}

/**
 * 一个词对到哪个词条：写法相同的词条里挑假名写法有这个读音的，还有几个时取这个写法常用的、排序分高的
 * （跟 src/main/dict.ts 的 word() 一个思路）。返回 { entry } 或 { problem }
 */
function matcher(db) {
  const byText = db.prepare('SELECT entry, common FROM form WHERE text = ?')
  // form 表按 (text, entry, kana) 存，按写法查才快
  const isKana = db.prepare('SELECT 1 FROM form WHERE text = ? AND entry = ? AND kana = 1')
  const entryOf = db.prepare(
    'SELECT id, head, reading, common, jlpt, score FROM entry WHERE id = ?'
  )
  return (written, reading) => {
    if (!reading) return { problem: '没写读音' }
    const forms = byText.all(written)
    if (!forms.length) return { problem: '词典里没有这个写法' }
    const cands = forms
      .filter((f) => isKana.get(reading, f.entry))
      .map((f) => ({ ...entryOf.get(f.entry), formCommon: f.common }))
      .sort((a, b) => b.formCommon - a.formCommon || b.score - a.score)
    const show = (e) => `${e.id} ${e.head}【${e.reading}】`
    if (!cands.length) {
      const others = forms.map((f) => show(entryOf.get(f.entry))).join('、')
      return { problem: `读音对不上（这个写法的词条：${others}）` }
    }
    const [a, b] = cands
    if (b && a.formCommon === b.formCommon && a.score === b.score)
      return { problem: `分不出是哪个词条：${cands.map(show).join('、')}` }
    return { entry: a }
  }
}

/** 等级：N5 → 5 … N1 → 1；不在 JLPT 表里的算 N3（见开头） */
const level = (e) => e.jlpt ?? 3

/** 本地日期 YYYY-MM-DD */
function today() {
  const d = new Date()
  const pad = (n) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`
}

/** 写成 JSON：一个词一行（跟 prettier 排出来的一样，跑 prettier 不会再改） */
function toJson(data) {
  const s = JSON.stringify
  const themes = data.themes.map((t) =>
    [
      '    {',
      `      "id": ${s(t.id)},`,
      `      "title": { "zh": ${s(t.title.zh)}, "en": ${s(t.title.en)} },`,
      '      "words": [',
      t.words.map(([id, w, r]) => `        [${id}, ${s(w)}, ${s(r)}]`).join(',\n'),
      '      ]',
      '    }'
    ].join('\n')
  )
  return `{\n  "generated": ${s(data.generated)},\n  "themes": [\n${themes.join(',\n')}\n  ]\n}\n`
}

function main() {
  if (!existsSync(DB)) throw new Error(`没有词典数据库 ${DB}，先跑 npm run data:ja`)
  const db = new DatabaseSync(DB, { readOnly: true })
  const match = matcher(db)
  const problems = []
  const themes = []
  /** 词条 → 出现在哪些主题（看重复得多不多） */
  const seen = new Map()
  const ids = new Set()
  for (const theme of THEMES) {
    if (ids.has(theme.id)) problems.push(`主题 id 重复：${theme.id}`)
    ids.add(theme.id)
    const words = []
    const byEntry = new Map()
    parseWords(theme.words).forEach(([written, reading], order) => {
      const r = match(written, reading)
      if (r.problem) {
        problems.push(
          `${theme.title.zh}：${written}${reading ? `【${reading}】` : ''} ${r.problem}`
        )
        return
      }
      const prev = byEntry.get(r.entry.id)
      if (prev) {
        problems.push(`${theme.title.zh}：${prev} 和 ${written} 对到同一个词条 ${r.entry.id}`)
        return
      }
      byEntry.set(r.entry.id, written)
      words.push({ ...r.entry, written, reading, order })
      seen.set(r.entry.id, [...(seen.get(r.entry.id) ?? []), `${written}·${theme.id}`])
    })
    words.sort((a, b) => level(b) - level(a) || b.common - a.common || a.order - b.order)
    themes.push({
      id: theme.id,
      title: theme.title,
      words: words.map((w) => [w.id, w.written, w.reading])
    })
    console.log(`${theme.title.zh}（${theme.id}）：${words.length} 个词`)
  }
  db.close()

  const shared = [...seen.values()].filter((v) => v.length > 1)
  if (shared.length)
    console.log(
      `在几个主题里都有的词（${shared.length} 个）：${shared.map((v) => v.join(' ')).join('；')}`
    )
  if (problems.length) {
    console.error(`\n有 ${problems.length} 个词要改，没写文件：`)
    for (const p of problems) console.error(`  ${p}`)
    process.exitCode = 1
    return
  }
  const total = themes.reduce((n, t) => n + t.words.length, 0)
  mkdirSync(dirname(out), { recursive: true })
  writeFileSync(out, toJson({ generated: today(), themes }))
  console.log(`写好 ${out}（${themes.length} 个主题，${total} 个词）`)
}

